@pytest.mark.parametrize("smtp_fails", [False, True])
def test_logs_hold_neither_token_nor_email_body(
    invite: Invite, caplog: pytest.LogCaptureFixture, smtp_fails: bool
) -> None:
    caplog.set_level(logging.DEBUG)  # every logger, every level, Celery included
    sent: list[tuple[str, str]] = []

    def fake_send_mail(subject: str, body: str, *args: Any, **kwargs: Any) -> int:
        sent.append((subject, body))
        if smtp_fails:
            raise smtplib.SMTPException("server said no")
        return 1

    with mock.patch("apps.accounts.tasks.send_mail", side_effect=fake_send_mail):
        invite()
    assert len(sent) == 1
    subject, body = sent[0]
    token = LINK.findall(body)[0]
    logged = caplog.text + "".join(str(r.args) for r in caplog.records)
    assert caplog.records  # the capture works: Celery's task trace is there
    assert token not in logged
    assert body.strip() not in logged
    assert subject not in logged
    assert "server said no" not in logged  # SMTP replies may echo the message


@pytest.mark.django_db(transaction=True)
def test_unexpected_task_error_does_not_leak_the_token(
    caplog: pytest.LogCaptureFixture,
) -> None:
    """An unhandled error makes Celery log a traceback: the token must not be in it."""
    from apps.accounts.tasks import send_invitation_email

    student = MembershipFactory.create(role=Role.PHD_STUDENT)
    with mock.patch("apps.accounts.tasks.send_invitation_email.delay"):
        inv = services.create_invitation(
            thesis=student.thesis,
            email="boom@example.org",
            role=Role.DIRECTOR,
            organization=student.organization,
            by=student.user,
        )
    caplog.set_level(logging.DEBUG)
    seen: list[str] = []

    def explode(subject: str, body: str, *args: Any, **kwargs: Any) -> int:
        seen.append(body)
        raise RuntimeError("unexpected")

    with (
        mock.patch("apps.accounts.tasks.send_mail", side_effect=explode),
        pytest.raises(RuntimeError),
    ):
        send_invitation_email.apply(args=[str(inv.pk)], throw=True)
    token = LINK.findall(seen[0])[0]
    assert token not in caplog.text
    inv.refresh_from_db()
    assert inv.token_hash is None  # rolled back: nothing usable left behind
