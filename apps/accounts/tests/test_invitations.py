# --------------------------------------------------------------------------- delivery state


def _state(inv: Invitation) -> Invitation.DeliveryState:
    return inv.delivery_state  # a call: mypy must not narrow it across clock changes


def test_delivery_states(invite: Invite, student: Membership) -> None:
    with time_machine.travel(NOW, tick=False):
        sent, _ = invite(email="a@example.org")
        queued = services.create_invitation(
            thesis=student.thesis,
            email="b@example.org",
            role=Role.DIRECTOR,
            organization=student.organization,
            by=student.user,
        )  # task never ran
    with time_machine.travel(NOW + dt.timedelta(minutes=5), tick=False):
        assert _state(sent) == Invitation.DeliveryState.SENT
        assert _state(queued) == Invitation.DeliveryState.QUEUED
    with time_machine.travel(NOW + dt.timedelta(minutes=11), tick=False):
        assert _state(queued) == Invitation.DeliveryState.NOT_SENT
    with time_machine.travel(NOW + dt.timedelta(hours=72), tick=False):
        assert _state(sent) == Invitation.DeliveryState.EXPIRED


