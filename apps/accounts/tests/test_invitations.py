def _open_link(client: Client, token: str) -> Any:
    """What the invitee does: open the e-mailed link, then click « Continuer »."""
    page = client.get(f"/invitation/{token}/")
    return page, client.post(reverse("invitation_continue"), {"token": token})


def _accept_new(client: Client, token: str, password: str = PASSWORD) -> Any:
    _open_link(client, token)
    return client.post(
        reverse("invitation_accept"),
        {"first_name": "Prenom", "last_name": "Nom", "password1": password, "password2": password},
    )


