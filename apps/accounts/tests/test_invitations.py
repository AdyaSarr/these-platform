@pytest.fixture
def invite(student: Membership, django_capture_on_commit_callbacks: Any) -> Invite:
    """Create an invitation as the student, run the e-mail task, return (invitation, token)."""

    def _invite(
        email: str = "invitee@example.org", role: Role = Role.DIRECTOR
    ) -> tuple[Invitation, str]:
        mail.outbox.clear()
        with django_capture_on_commit_callbacks(execute=True):
            inv = services.create_invitation(
                thesis=student.thesis,
                email=email,
                role=role,
                organization=OrganizationFactory.create(),
                by=student.user,
            )
        inv.refresh_from_db()
        tokens = LINK.findall(str(mail.outbox[-1].body)) if mail.outbox else []
        return inv, (tokens[0] if tokens else "")

    return _invite


