@pytest.mark.django_db(transaction=True)
def test_concurrent_acceptances_succeed_only_once() -> None:
    """Two simultaneous acceptances of one invitation: exactly one wins (row lock)."""
    student = MembershipFactory.create(role=Role.PHD_STUDENT)
    existing = UserFactory.create(email="race@example.org")
    inv = services.create_invitation(
        thesis=student.thesis,
        email="race@example.org",
        role=Role.DIRECTOR,
        organization=student.organization,
        by=student.user,
    )
    Invitation.objects.filter(pk=inv.pk).update(
        token_hash=crypto.hash_token(crypto.new_token()),
        email_status=Invitation.EmailStatus.SENT,
        expires_at=timezone.now() + dt.timedelta(hours=72),
    )
    barrier = threading.Barrier(2)
    results: list[str] = []

    def worker() -> None:
        try:
            barrier.wait()
            services.accept_invitation(inv.pk, user=existing)
            results.append("ok")
        except InvalidInvitationError:
            results.append("refused")
        finally:
            connection.close()

    threads = [threading.Thread(target=worker) for _ in range(2)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert sorted(results) == ["ok", "refused"]
    assert Membership.objects.filter(user=existing).count() == 1


